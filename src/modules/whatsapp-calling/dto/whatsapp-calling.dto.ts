import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

export class EnableWhatsappCallingSettingsDto {
  @ApiPropertyOptional({
    description: 'Optional WABA Phone Number ID override (defaults to tenant active WABA number)',
    example: '109283746510293',
  })
  phoneNumberId?: string;

  @ApiPropertyOptional({
    description: 'Meta WhatsApp call icon visibility on business profile',
    enum: ['DEFAULT', 'DISABLE_ALL'],
    default: 'DEFAULT',
  })
  callIconVisibility?: 'DEFAULT' | 'DISABLE_ALL';

  @ApiPropertyOptional({
    description: 'Enable callback permission requests on WABA phone number',
    enum: ['ENABLED', 'DISABLED'],
    default: 'ENABLED',
  })
  callbackPermissionStatus?: 'ENABLED' | 'DISABLED';
}

export class RequestWhatsappCallPermissionDto {
  @ApiPropertyOptional({
    description: 'Optional custom message body shown inside the interactive WhatsApp call permission request',
    example:
      'Namaste! Can our team call you on WhatsApp to walk through your quotation and dispatch timeline?',
  })
  reasonText?: string;

  @ApiPropertyOptional({
    description: 'Optional conversation thread ID to log the timeline card into directly',
  })
  conversationId?: string;
}

export class StartOutboundWhatsappCallDto {
  @ApiProperty({
    description: 'Target CRM Lead ID (raw phone is resolved server-side to preserve phone masking)',
    example: '665f1a2b3c4d5e6f7a8b9c0d',
  })
  leadId!: string;

  @ApiProperty({
    description: 'WebRTC SDP Offer generated by the agent browser RTCPeerConnection',
    example: 'v=0\r\no=- 4611731400430051336 2 IN IP4 127.0.0.1\r\ns=-\r\nt=0 0\r\n...',
  })
  sdpOffer!: string;

  @ApiPropertyOptional({
    description: 'Optional linked Inbox conversation ID',
  })
  conversationId?: string;
}

export class AcceptInboundWhatsappCallDto {
  @ApiProperty({
    description: 'WebRTC SDP Answer generated by the answering agent browser RTCPeerConnection',
    example: 'v=0\r\no=- 4611731400430051336 2 IN IP4 127.0.0.1\r\ns=-\r\nt=0 0\r\n...',
  })
  sdpAnswer!: string;
}

export class TerminateWhatsappCallDto {
  @ApiPropertyOptional({
    description: 'Optional measured connected call duration in seconds from client if server connectedAt was not set',
    example: 74,
  })
  durationSeconds?: number;

  @ApiPropertyOptional({
    description: 'Optional reason for rejection or termination',
    example: 'agent_hangup',
  })
  reason?: string;
}

export class UploadWhatsappCallRecordingDto {
  @ApiProperty({
    description: 'Base64 data URL (audio/webm, audio/ogg, audio/mp4) or HTTPS URL of captured WebRTC call audio',
    example: 'data:audio/webm;base64,GkXfo59ChoEBQveBAULygQRC84EIQoKEd2VibUKHgQRChYECGFOAZwH/////////',
  })
  audioDataUrl!: string;

  @ApiPropertyOptional({
    description: 'Optional call duration in seconds',
    example: 74,
  })
  durationSeconds?: number;
}

export class TopupCallingWalletDto {
  @ApiProperty({
    description: 'Amount in INR to credit into the workspace WhatsApp Calling wallet',
    example: 500,
  })
  amountInr!: number;

  @ApiPropertyOptional({
    description: 'Optional note or payment reference for audit log',
    example: 'Starter team calling recharge',
  })
  note?: string;
}
